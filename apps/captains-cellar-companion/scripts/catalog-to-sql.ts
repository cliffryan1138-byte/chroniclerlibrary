// Turns reviewed catalog files into SQL to paste into the Supabase SQL editor.
//   npm run catalog:sql -- catalog/makers/tabanero.json > catalog/makers/tabanero.sql
//   npm run catalog:sql -- catalog/makers/*.json > catalog/all-makers.sql
//   npm run catalog:sql -- catalog/pipe-tobacco/*.json > catalog/all-blends.sql   # the category comes from each file
// Each maker is upserted first, then its cigars or blends, linked to it. Re-running updates instead of duplicating:
// makers match by name (ignoring case and spacing) and item ids derive from category + maker + name.
import { readFileSync } from 'node:fs'
import { CATEGORY, type CatalogEntry, type MakerFile } from '../src/branches/cigar'
import { catalogId, sqlQuote as q } from './catalog-ids'
import { cigarTaxonomy } from '../src/branches/cigar'
import { pipeTaxonomy } from '../src/branches/pipe'

// Files can be hand-made (see catalog/BROWSER_CLAUDE.md), so nothing reaches the SQL unchecked.
const FAMILIES: Record<string, Set<string>> = {
  cigar: new Set(cigarTaxonomy.families.map((f) => f.id)),
  pipe_tobacco: new Set(pipeTaxonomy.families.map((f) => f.id)),
}
const problems: string[] = []

const files = process.argv.slice(2)
if (!files.length) {
  console.error('usage: npm run catalog:sql -- catalog/makers/<maker>.json [more.json ...] > out.sql')
  process.exit(1)
}

const keyOf = (name: string) => `lower(regexp_replace(btrim(${q(name)}), '\\s+', ' ', 'g'))`
const lines = ['-- GENERATED by scripts/catalog-to-sql.ts from ' + files.join(', ') + '. Review the JSON, not this file.', 'begin;']
let makers = 0
let count = 0

for (const file of files) {
  const raw = JSON.parse(readFileSync(file, 'utf8')) as MakerFile | { source?: string; entries: CatalogEntry[] }
  // Maker files carry a maker header; an older store-wide file is grouped by each entry's brand.
  const groups: { maker: MakerFile['maker']; category: string; entries: CatalogEntry[] }[] = 'maker' in raw
    ? [{ maker: raw.maker, category: raw.category ?? CATEGORY, entries: raw.entries }]
    : [...new Set(raw.entries.map((e) => e.brand).filter(Boolean))].map((brand) => ({
      maker: { name: brand }, category: CATEGORY, entries: raw.entries.filter((e) => e.brand === brand),
    }))

  for (const g of groups) {
    const families = FAMILIES[g.category]
    if (!families) { problems.push(`${file}: unknown category "${g.category}" (cigar or pipe_tobacco)`); continue }
    if (!g.maker?.name?.trim()) { problems.push(`${file}: the maker has no name`); continue }
    lines.push(
      `insert into public.makers (name, website, country, status) values (${q(g.maker.name)}, ${g.maker.website ? q(g.maker.website) : 'null'}, ${g.maker.country ? q(g.maker.country) : 'null'}, 'curated')`,
      `  on conflict (name_key) do update set status = 'curated', website = coalesce(excluded.website, makers.website), country = coalesce(excluded.country, makers.country);`,
    )
    makers++
    const makerId = `(select id from public.makers where name_key = ${keyOf(g.maker.name)})`
    for (const e of g.entries) {
      if (!e.name?.trim()) { problems.push(`${file}: an entry has no name`); continue }
      if (e.attributes != null && (typeof e.attributes !== 'object' || Array.isArray(e.attributes))) { problems.push(`${file}: ${e.name}: attributes must be an object`); continue }
      for (const t of e.tags ?? []) if (!families.has(t.family)) problems.push(`${file}: ${e.name}: "${t.family}" isn't a ${g.category} flavor family (${[...families].join(', ')})`)
      if (e.strength != null && !(typeof e.strength === 'number' && e.strength >= 1 && e.strength <= 5)) problems.push(`${file}: ${e.name}: strength must be 1-5 or null`)
      const brand = g.maker.name
      const id = catalogId(g.category, brand, e.name)
      const strength = e.strength != null && e.strength >= 1 && e.strength <= 5 ? Math.round(e.strength) : 'null'
      const attributes = { ...e.attributes, ...(e.sources?.length ? { sources: e.sources } : {}) }
      delete (attributes as Record<string, unknown>).source
      // The item shows the maker record's spelling, whatever case the file used.
      const brandSql = `coalesce((select name from public.makers where name_key = ${keyOf(brand)}), ${q(brand)})`
      lines.push(
        `insert into public.items (id, category, brand, name, attributes, strength, status, maker_id) values (${q(id)}, ${q(g.category)}, ${brandSql}, ${q(e.name)}, ${q(JSON.stringify(attributes))}::jsonb, ${strength}, 'curated', ${makerId})`,
        `  on conflict (id) do update set brand = excluded.brand, name = excluded.name, attributes = excluded.attributes, strength = excluded.strength, status = 'curated', maker_id = excluded.maker_id;`,
        `delete from public.item_tags where item_id = ${q(id)};`,
      )
      for (const t of e.tags ?? []) {
        lines.push(`insert into public.item_tags (item_id, family, descriptor, weight) values (${q(id)}, ${q(t.family)}, ${t.descriptor ? q(t.descriptor) : 'null'}, ${Math.max(0, Math.min(1, t.weight))});`)
      }
      count++
    }
  }
}
if (problems.length) {
  console.error(`Not written: fix these first\n  ${problems.join('\n  ')}`)
  process.exit(1)
}
lines.push('commit;', `-- ${makers} maker(s), ${count} items`)
console.log(lines.join('\n'))
